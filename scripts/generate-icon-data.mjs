// Extracts the icons this site actually uses out of the Iconify collections.
//
// Run with `npm run icons:data`. Iconify is the source of truth — icons are
// chosen by their real name from icones.js.org — but the collections are single
// multi-megabyte JSON objects that no bundler can tree-shake, since each is one
// object. @iconify-json/simple-icons alone is thousands of brand marks.
//
// Rather than keep a hand-written list of what is used, which drifts the moment
// someone adds an icon, this SCANS the source for Iconify names and pulls out
// exactly what it finds. Adding an icon anywhere in src/ is all it takes.

import { writeFile, mkdir, readdir, readFile } from "node:fs/promises";
import { dirname, join, extname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "src");
const OUT = join(root, "src/components/icons/data.ts");
/**
 * Generated files are outputs, not sources.
 *
 * stack-index.ts lists six thousand icon names for the search box; scanning it
 * would inline every one of their bodies into the bundle, which is the exact
 * thing this script exists to prevent.
 */
const SKIP = new Set([OUT, join(root, "src/lib/stack-index.ts")]);

/** Collections we are willing to pull from. */
const PREFIXES = ["material-symbols", "simple-icons"];

// Written as a literal, not built from PREFIXES: in a template string a lone
// backslash-b is the backspace character, not a word boundary, so the built
// version matched nothing while still being a perfectly legal regex.
const NAME_RE = /(?:material-symbols|simple-icons):[a-z0-9-]+/g;
const SOURCE_EXT = new Set([".ts", ".tsx", ".js", ".jsx"]);

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else if (SOURCE_EXT.has(extname(entry.name))) yield path;
  }
}

const used = new Set();
for await (const file of walk(SRC)) {
  if (SKIP.has(file)) continue;
  for (const match of (await readFile(file, "utf8")).matchAll(NAME_RE)) used.add(match[0]);
}

const names = [...used].sort();
if (!names.length) throw new Error("No Iconify names found in src/ — that cannot be right.");

const collections = new Map();
const out = {};

for (const full of names) {
  const [prefix, name] = full.split(":");
  if (!PREFIXES.includes(prefix)) throw new Error(`Not a collection we pull from: ${prefix}`);
  if (!collections.has(prefix)) collections.set(prefix, require(`@iconify-json/${prefix}`).icons);
  const set = collections.get(prefix);
  const icon = set.icons[name];
  if (!icon) throw new Error(`Icon not found in @iconify-json/${prefix}: ${name}`);
  out[full] = {
    body: icon.body,
    width: icon.width ?? set.width ?? 16,
    height: icon.height ?? set.height ?? 16,
  };
}

const body = `// GENERATED by scripts/generate-icon-data.mjs -- do not edit.
// It scans src/ for Iconify names; use one anywhere and re-run \`npm run icons:data\`.

export type IconName = ${names.map((n) => JSON.stringify(n)).join(" | ")};

export const ICONS: Record<IconName, { body: string; width: number; height: number }> = ${JSON.stringify(
  out,
  null,
  2
)};
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body);
console.log(`icon data: ${names.length} icon(s) -> src/components/icons/data.ts`);
for (const n of names) console.log(`  ${n}`);
