// Builds tiny font files containing ONLY the characters this site needs from a
// given family.
//
// Run with `npm run fonts:subset`, and re-run it whenever a SUBSET changes. The
// resulting .woff2 files are committed, so the build itself never touches the
// network.
//
// Google's CSS API takes a `text=` parameter and returns a face subset to
// exactly those codepoints, which is how a handful of characters costs a couple
// of kilobytes instead of a megabyte.

import { writeFile, mkdir, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(root, "src/app/fonts");

const SUBSETS = [
  {
    // Why this exists: next/font/google only offers ZCOOL XiaoWei's `latin`
    // subset — Google marks `chinese-simplified` experimental and Next's font
    // data leaves it out, so the loader cannot produce a file with any Chinese
    // glyphs in it at all. Without this the text falls through to whatever CJK
    // font the visitor happens to have.
    family: "ZCOOL+XiaoWei",
    characters: "因为热爱",
    file: "zcool-xiaowei-subset.woff2",
    constant: "ZCOOL_RANGE",
  },
  {
    // Cabin's @ is the one glyph in the family that lets the page down, and it
    // turns up in three places that matter: the role line, the handle, and the
    // email address. Rather than change the body font over one character, this
    // pulls @ alone out of Inter and the stack in globals.css puts it ahead of
    // Cabin, scoped by unicode-range so it can never affect anything else.
    family: "Inter",
    characters: "@",
    file: "inter-at-subset.woff2",
    constant: "AT_RANGE",
  },
];

// Google serves woff2 only to user agents it believes support it; the default
// fetch UA gets an older format back, or nothing.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

await mkdir(OUT_DIR, { recursive: true });

const ranges = [];
const lines = [
  "// GENERATED by scripts/generate-font-subsets.mjs -- do not edit.",
  "// Run `npm run fonts:subset` after changing the characters in that script.",
  "",
];

for (const { family, characters, file, constant } of SUBSETS) {
  const name = family.replace("+", " ");
  const cssUrl =
    "https://fonts.googleapis.com/css2?family=" +
    family +
    "&text=" +
    encodeURIComponent(characters) +
    "&display=swap";

  const css = await fetch(cssUrl, { headers: { "User-Agent": UA } }).then((r) => {
    if (!r.ok) throw new Error(`Google CSS API for ${name}: ${r.status} ${r.statusText}`);
    return r.text();
  });

  const fontUrl = css.match(/src:\s*url\(([^)]+)\)\s*format\('woff2'\)/)?.[1];
  if (!fontUrl) throw new Error(`No woff2 in the response for ${name}:\n${css}`);

  const range = css.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();
  if (!range) throw new Error(`No unicode-range in the response for ${name}`);

  const font = await fetch(fontUrl, { headers: { "User-Agent": UA } }).then((r) => {
    if (!r.ok) throw new Error(`Font download for ${name}: ${r.status} ${r.statusText}`);
    return r.arrayBuffer();
  });

  await writeFile(join(OUT_DIR, file), Buffer.from(font));

  lines.push(`/** ${name}, subset to: ${characters} */`);
  lines.push(`export const ${constant} = ${JSON.stringify(range)};`);
  ranges.push({ constant, range });
  lines.push("");

  console.log(`${name}: ${characters}`);
  console.log(`  unicode-range: ${range}`);
  console.log(`  ${(font.byteLength / 1024).toFixed(1)} KB -> src/app/fonts/${file}`);
}

// The unicode-range has to match what is actually inside each file. Emitting it
// rather than copying it by hand means changing the characters above cannot
// leave a stale range behind in fonts.ts, which would either hide glyphs that
// are present or pull down a file for characters it does not contain.
await writeFile(join(OUT_DIR, "ranges.ts"), lines.join("\n"));
console.log("  src/app/fonts/ranges.ts");

// next/font will not accept an imported value for unicode-range — it demands a
// literal — so fonts.ts has to spell each range out. That is a second copy, and
// a second copy silently going stale is exactly the failure this script exists
// to prevent, so check it rather than trusting it.
const fontsTs = await readFile(join(root, "src/app/fonts.ts"), "utf8");
const stale = ranges.filter(({ range }) => !fontsTs.includes(range));
if (stale.length) {
  console.error("\nsrc/app/fonts.ts is out of date. Update these unicode-range values:");
  for (const { constant, range } of stale) console.error(`  ${constant}: "${range}"`);
  process.exit(1);
}
console.log("  src/app/fonts.ts ranges verified");
