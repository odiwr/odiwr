// The searchable tech-stack vocabulary.
//
// Run with `npm run stacks`. Four Iconify collections are merged: Simple Icons
// for brands, plus Devicon, Logos and Skill Icons, which between them cover the
// development and embedded tooling Simple Icons does not carry.
//
// Entries are keyed "prefix:name" so /icon can serve any of them, and are
// deduplicated by title with the collections in preference order — one "Arduino"
// rather than four.
//
// This is an index of NAMES, about 200KB of text and no artwork. The marks
// themselves are fetched one at a time, so a vocabulary this size costs nothing
// to render.

import { writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Preference order: the first collection to claim a title keeps it. */
const COLLECTIONS = ["simple-icons", "devicon", "logos", "skill-icons"];

/** Simple Icons ships real product names; the others only have icon slugs. */
const simple = require("simple-icons");
const titles = new Map();
for (const key of Object.keys(simple)) {
  const icon = simple[key];
  if (icon?.slug && icon?.title) titles.set(icon.slug, icon.title);
}

/** "raspberrypi-wordmark" -> "Raspberrypi Wordmark" */
function prettify(name) {
  return name
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

const rows = [];
const seen = new Set();

for (const prefix of COLLECTIONS) {
  const collection = require(`@iconify-json/${prefix}`).icons;
  for (const name of Object.keys(collection.icons)) {
    const title = prefix === "simple-icons" ? (titles.get(name) ?? prettify(name)) : prettify(name);
    const dedupe = title.toLowerCase();
    if (seen.has(dedupe)) continue;
    seen.add(dedupe);
    rows.push([`${prefix}:${name}`, title]);
  }
}

rows.sort((a, b) => a[1].localeCompare(b[1]));

const body = `// GENERATED by scripts/generate-stack-index.mjs -- do not edit.
// Run \`npm run stacks\` to refresh.

/** ["prefix:name", title] for every mark available as a stack tag. */
export const STACK_INDEX: readonly (readonly [string, string])[] = ${JSON.stringify(rows)};

const TITLES = new Map(STACK_INDEX);

/** Human name for an icon key; the key itself if it is not a known mark. */
export function stackTitle(key: string): string {
  return TITLES.get(key) ?? key.replace(/^[a-z-]+:/, "");
}

export function isStack(key: string): boolean {
  return TITLES.has(key);
}
`;

await writeFile(join(root, "src/lib/stack-index.ts"), body);
console.log(`stack index: ${rows.length} marks from ${COLLECTIONS.length} collections`);
